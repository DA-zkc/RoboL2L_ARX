"""Ports implemented by installed station components (no vendor imports)."""
from typing import Protocol
from .contracts import RobotState,Observation,Trajectory,ExecutionResult,IKResult
from .cameras import Frame

class CameraSource(Protocol):
    def open(self) -> None: ...
    def read(self) -> Frame: ...
    def close(self) -> None: ...

class StationAdapter(Protocol):
    synthetic: bool
    cameras: dict
    def describe(self) -> dict: ...
    def binding(self) -> str: ...
    def get_robot_state(self) -> RobotState: ...
    def get_observation(self,camera_names=None) -> Observation: ...
    def solve_ik(self,target,seed=None) -> IKResult: ...
    def plan_motion(self,goal,*,start_joints=None,speed_factor=None,interpolation_dt_s=None,maximum_trajectory_dt_s=None) -> tuple[Trajectory,object]: ...
    def prepare_trajectory(self,trajectory:Trajectory) -> object: ...
    def execute(self,payload,trajectory) -> ExecutionResult: ...
    def check_gripper(self,position) -> str | None: ...
    def set_gripper(self,position) -> ExecutionResult: ...
    def check_close_gripper(self) -> str | None: ...
    def close_gripper(self) -> ExecutionResult: ...
    def close(self) -> None: ...
